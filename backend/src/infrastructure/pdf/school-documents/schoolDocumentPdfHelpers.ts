import PDFDocument from "pdfkit";
import QRCode from "qrcode";
import type { Language, SchoolInfo } from "./schoolDocumentPdfTypes";

export type PdfDoc = InstanceType<typeof PDFDocument>;

export function finalizePdf(
  doc: PdfDoc,
  build: (doc: PdfDoc) => Promise<void>
): Promise<Buffer> {
  return new Promise(async (resolve, reject) => {
    const buffers: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => buffers.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(buffers)));
    doc.on("error", reject);
    try {
      await build(doc);
    } catch (err) {
      reject(err);
      return;
    }
    doc.end();
  });
}

export function drawHeader(
  doc: PdfDoc,
  school: SchoolInfo,
  title: string
): void {
  doc.rect(0, 0, 595, 80).fill("#1e3a5f");

  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor("white")
    .text("RÉPUBLIQUE DU CAMEROUN", 40, 12, { align: "left", width: 230 })
    .text("Paix — Travail — Patrie", 40, 22, { align: "left", width: 230 });

  doc
    .fontSize(7)
    .fillColor("white")
    .text("REPUBLIC OF CAMEROON", 320, 12, { align: "right", width: 235 })
    .text("Peace — Work — Fatherland", 320, 22, { align: "right", width: 235 });

  doc
    .fontSize(11)
    .font("Helvetica-Bold")
    .fillColor("white")
    .text(school.name.toUpperCase(), 40, 36, { align: "center", width: 515 });

  if (school.motto) {
    doc
      .fontSize(8)
      .font("Helvetica-Oblique")
      .fillColor("#cbd5e1")
      .text(`"${school.motto}"`, 40, 52, { align: "center", width: 515 });
  }

  if (school.ville || school.bp || school.tel) {
    const contact = [school.bp && `B.P. ${school.bp}`, school.ville, school.tel && `Tél: ${school.tel}`]
      .filter(Boolean)
      .join(" | ");
    doc
      .fontSize(7)
      .font("Helvetica")
      .fillColor("#94a3b8")
      .text(contact, 40, 64, { align: "center", width: 515 });
  }

  doc.fillColor("black");

  doc
    .rect(40, 95, 515, 28)
    .fillAndStroke("#f0f4f8", "#1e3a5f");

  doc
    .fontSize(13)
    .font("Helvetica-Bold")
    .fillColor("#1e3a5f")
    .text(title, 40, 102, { align: "center", width: 515 });

  doc.fillColor("black");
  doc.y = 140;
}

export async function drawQr(
  doc: PdfDoc,
  url: string,
  x: number,
  y: number,
  lang: Language,
  size: number = 70
): Promise<void> {
  const qrBuffer = await QRCode.toBuffer(url, { type: "png", margin: 1, width: 200 });
  doc.image(qrBuffer, x, y, { fit: [size, size] });

  doc
    .fontSize(6)
    .font("Helvetica")
    .fillColor("#64748b")
    .text(lang === "en" ? "Scan to verify" : "Scannez pour vérifier", x, y + size + 3, {
      width: size,
      align: "center",
    });
}

export function dataRow(
  doc: PdfDoc,
  label: string,
  value: string,
  y: number
): void {
  doc.fontSize(10).font("Helvetica-Bold").fillColor("#334155").text(label, 60, y);
  doc.fontSize(10).font("Helvetica").fillColor("#0f172a").text(value, 240, y);
  doc.moveTo(60, y + 14).lineTo(535, y + 14).strokeColor("#e2e8f0").stroke();
}

export function formatDocumentDate(date: Date, lang: Language): string {
  return date.toLocaleDateString(lang === "en" ? "en-GB" : "fr-FR", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

export function drawSignatureBlock(doc: PdfDoc, lang: Language): void {
  const signataire = lang === "en" ? "The Principal / Head of School" : "Le Proviseur / Directeur";
  doc
    .fontSize(10)
    .font("Helvetica-Bold")
    .fillColor("#1e3a5f")
    .text(signataire, 60, doc.y, { align: "right", width: 475 });

  doc.y += 15;
  const cachet = lang === "en" ? "(Signature and official stamp)" : "(Signature et cachet officiel)";
  doc
    .fontSize(8)
    .font("Helvetica-Oblique")
    .fillColor("#94a3b8")
    .text(cachet, 60, doc.y, { align: "right", width: 475 });
}

export async function drawDocumentFooterWithQr(
  doc: PdfDoc,
  documentId: string,
  verifyUrl: string,
  lang: Language
): Promise<void> {
  const qrY = doc.page.height - 130;
  await drawQr(doc, verifyUrl, 60, qrY, lang, 70);

  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor("#94a3b8")
    .text(`Document N° ${documentId.slice(0, 8).toUpperCase()}`, 60, qrY + 80, {
      width: 200,
    });

  doc.rect(0, doc.page.height - 22, 595, 22).fill("#1e3a5f");
  const footer = lang === "en"
    ? "Document generated by ZekoulABia — Verifiable via QR Code"
    : "Document généré par ZekoulABia — Vérifiable à l'adresse indiquée par le QR Code";
  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor("white")
    .text(footer, 40, doc.page.height - 15, {
      align: "center",
      width: 515,
    });
}
